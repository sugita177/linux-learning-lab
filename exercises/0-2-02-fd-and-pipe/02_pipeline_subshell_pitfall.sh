#!/usr/bin/env bash

# ==============================================================================
# [実務の重要知識] while IFS= read -r line; do ... done イディオムの分解解説
#
# 1. while <cmd>; do ... done
#    - Bashのwhileは「コマンドの終了ステータスが0（成功）の間」ループを継続する。
#    - ';' はコマンドの区切り。改行せずに 'do' を続けるために必須。
# 2. read line
#    - 標準入力（FD 0）から1行読み込んで変数 'line' に格納する。
#    - 入力の末尾（EOF）に達すると終了ステータス1を返すため、whileが自然に終了する。
# 3. -r (raw mode)
#    - バックスラッシュ '\' をエスケープ文字として解釈させず、そのまま保持する（実務必須）。
# 4. IFS= (Internal Field Separator)
#    - 空白・タブなどの区切り文字を無効化し、行頭・行末のインデントが勝手に消去（trim）されるのを防ぐ。
# ==============================================================================

echo "=== 1. 罠のパターン: パイプラインによるループ ==="
# 【原因】
# Linuxカーネルのパイプ '|' は、右辺のコマンドを別プロセス（サブシェル/fork）として実行する。
# そのため、ループ内で更新した 'count' は子プロセスのメモリ空間にしか存在せず、
# ループ終了（子プロセス消滅）とともに親環境からは消えてしまう。
count=0
printf "apple\nbanana\norange\n" | while IFS= read -r line; do
    count=$((count + 1))
    echo "  [パイプ内] line: $line, count: $count"
done
echo "=> ループ外の最終 count: $count (0のままリセットされる)"

echo
echo "=== 2. 解決パターン: プロセス置換 < <(...) ==="
# 【解決の原理】
# '< <(コマンド)' は「プロセス置換」と呼ばれるBashの強力な機能。
# 左辺の 'while' ループは「メインシェル自身（同一プロセス）」で実行される。
# そして、右辺の <(...) の出力を、あたかもファイルのように標準入力（FD 0）から流し込む。
# そのため、ループ内で更新した変数がそのままメイン環境に保持される。
count=0
while IFS= read -r line; do
    count=$((count + 1))
    echo "  [プロセス置換] line: $line, count: $count"
done < <(printf "apple\nbanana\norange\n")
echo "=> ループ外の最終 count: $count (正常に3が保持される)"